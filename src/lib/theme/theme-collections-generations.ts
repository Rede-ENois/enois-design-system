/** Relevo em duas camadas (face clara em cima, sombra embaixo), como nos clássicos. */
function bevel(light: string, light2: string, dark: string, dark2: string) {
  return {
    "--bevel-light": light,
    "--bevel-light-2": light2,
    "--bevel-dark": dark,
    "--bevel-dark-2": dark2,
  };
}

/** Textura de tubo: duas linhas de 2px alternadas, sem animação e sem camada extra. */
function scanlines(base: string, line: string): string {
  return `repeating-linear-gradient(0deg, ${base} 0 2px, ${line} 2px 4px)`;
}

